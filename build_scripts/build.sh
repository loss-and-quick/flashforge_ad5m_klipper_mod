#!/bin/bash
# Build Wrapper Script for AD5M Klipper Mod
set -e

SCRIPT_DIR=$( cd -- "$( dirname -- "${BASH_SOURCE[0]}" )" &> /dev/null && pwd )
source $SCRIPT_DIR/env.sh

MULTICORE=-j$(nproc)

# MCU firmware selection, see mcu_env
MCU_CONFIGS=$BUILD_SCRIPTS/components/mcu_configs
MCU_DEFAULT=stm32f103

#####################################################
###### Buildroot Common Build Helper Functions ######
#####################################################

# initialize a buildroot build dir with config
buildroot_prepare() # args: path config_generator
{
	br_path="$1";
	br_name=$(basename "$1")
	br_config_generator="$2"

	mkdir -p "$br_path"
	pushd "$br_path" > /dev/null

	# setup make environment, use external tree
    if [ ! -f Makefile ]; then
  		make O="$PWD" BR2_EXTERNAL="$BUILDROOT_EXT" -C "$BUILDROOT_GIT" $MULTICORE allnoconfig
    fi

	# backup old config
  	if [ -f .config ]; then
	    mv .config .config_old
    fi

	# generate new config from defconfigs
    $br_config_generator
    make $MULTICORE olddefconfig

	# restore old config if unchanged (keep timestamp)
    if [ -f .config_old ] && cmp --silent .config .config_old
    then
  	    mv -f .config_old .config
  	    log_info "$br_name: config up to date"
    else
        rm -f .config_old
        log_info "$br_name: config initialized"
    fi

    popd > /dev/null
}

# (re-)build a buildroot project
buildroot_build_always() # args: path make_command
{
	br_path="$1";
	br_name=$(basename "$1")
	br_make="$2 $MULTICORE"

	pushd "$br_path" > /dev/null

	if [ -e "host" ] || [ -e "images" ] || [ -e "target" ] || \
	   find build/ -mindepth 1 -maxdepth 1 ! -name buildroot-config 2> /dev/null | read; then
	   log_warn "unclean build of $br_name"
	fi

	if $br_make
	then
		log_info "$br_name: build done"
	else
		log_error "$br_name: build failed"
		exit 1
	fi

	popd > /dev/null
}


# (re-)build a buildroot build dir if not uptodate
buildroot_build_if_needed() # args: path make_command target_file
{
	br_path="$1";
	br_name=$(basename "$1")
	br_make="$2 $MULTICORE"
	br_target_file="$3"

	pushd "$br_path" > /dev/null

	if [ -f "$br_target_file" ] && [ "$br_target_file" -nt .config ]
	then
		log_info "$br_name: target up to date"
	else
		buildroot_build_always "$br_path" "$br_make"
	fi

	popd > /dev/null
}

###########################################
###### Buildroot Mod SDK Build Steps ######
###########################################

defconfig_sdk() {
    cp "$BUILDROOT_CONFIGS/sdk" "$BUILDROOT_SDK/.config"
}

prepare_sdk() {
	buildroot_prepare "$BUILDROOT_SDK" "defconfig_sdk"
}

build_sdk() {
	br_image=( "$BUILDROOT_SDK"/images/*sdk-buildroot.tar.gz )
	buildroot_build_if_needed "$BUILDROOT_SDK" "make sdk"  "$br_image"
}

rebuild_sdk() {
	buildroot_build_always "$BUILDROOT_SDK" "make sdk"
}

clean_sdk() {
  rm -rf "$BUILDROOT_SDK"
}

package_sdk()
{
	br_image=( "$BUILDROOT_SDK"/images/*sdk-buildroot.tar.gz )
	sdk_name="KlipperMod-SDK-$GIT_VERSION.tar.xz"
	mkdir -p $BUILD_PACKAGE
	gzip -dc "$br_image" | xz -T`nproc` > $BUILD_PACKAGE/$sdk_name
	log_info "sdk: created $sdk_name"
}

###############################################
###### Buildroot Mod Variant Build Steps ######
###############################################

# resolve the MCU of each board and the suffix that keeps their builds apart
mcu_env()
{
	eboard_mcu="${EBOARD_MCU:-${MCU:-$MCU_DEFAULT}}"
	mainboard_mcu="${MAINBOARD_MCU:-${MCU:-$MCU_DEFAULT}}"

	for board in "eboard_$eboard_mcu" "mcu_$mainboard_mcu" \
	             "katapult_eboard_$eboard_mcu" "katapult_mcu_$mainboard_mcu"; do
		if [ ! -f "$MCU_CONFIGS/$board" ]; then
			log_error "MCU config not found: $MCU_CONFIGS/$board"
			exit 1
		fi
	done

	# the default MCU keeps the plain build directory and package name
	mcu_suffix=""
	if [ "$eboard_mcu" = "$mainboard_mcu" ]; then
		[ "$eboard_mcu" = "$MCU_DEFAULT" ] || mcu_suffix="-$eboard_mcu"
	else
		[ "$eboard_mcu" = "$MCU_DEFAULT" ] || mcu_suffix="-eboard_$eboard_mcu"
		[ "$mainboard_mcu" = "$MCU_DEFAULT" ] || mcu_suffix="$mcu_suffix-mainboard_$mainboard_mcu"
	fi
}

variant_env()
{
	variant=$1

	mcu_env

	# add plugins suffix to build directory name if plugins are used
	plugin_suffix=""
	if [ -n "$WITH_PLUGINS" ]; then
		plugin_suffix="-$(echo "$WITH_PLUGINS" | tr ' ' '\n' | sort | tr '\n' '-' | sed 's/-$//')"
	fi

    br_builddir="$BUILDROOT_OUT/variant-$variant$mcu_suffix$plugin_suffix"
	br_image="$br_builddir/images/rootfs.tar"
	br_chroot="$br_builddir/images/chroot.tar.xz"
}

defconfig_variant() {
    variant_env $1
    pushd $br_builddir
  	# merge config fragments to .config
  	merge_configs=("$BUILDROOT_CONFIGS/sdk" "$BUILDROOT_CONFIGS/base" "$BUILDROOT_CONFIGS/variant-$variant")

  	# the MCU firmwares to build are selected per board, see mcu_env
  	{
  		echo "# generated by build.sh, do not edit"
  		echo "BR2_PACKAGE_KLIPPER_CONFIGS=\"$MCU_CONFIGS/eboard_$eboard_mcu $MCU_CONFIGS/mcu_$mainboard_mcu\""
  		echo "BR2_PACKAGE_KATAPULT_CONFIGS=\"$MCU_CONFIGS/katapult_eboard_$eboard_mcu $MCU_CONFIGS/katapult_mcu_$mainboard_mcu\""
  	} > "$br_builddir/mcu.config"
  	merge_configs+=("$br_builddir/mcu.config")
  	log_info "variant-$variant: eboard=$eboard_mcu mainboard=$mainboard_mcu"

  	# eMMC clock tuning
  	{
  		if [ "$EMMC_OVERCLOCK" = "1" ]; then
  			echo "BR2_PACKAGE_AD5M_EMMC_OVERCLOCK=y"
  		else
  			echo "BR2_PACKAGE_AD5M_EMMC_OVERCLOCK=n"
  		fi
  	} > "$br_builddir/emmc.config"
  	merge_configs+=("$br_builddir/emmc.config")
  	log_info "variant-$variant: emmc_overclock=$EMMC_OVERCLOCK"

  	# add plugin configs if WITH_PLUGINS is set
  	if [ -n "$WITH_PLUGINS" ]; then
  		log_info "Adding plugins to variant-$variant: $WITH_PLUGINS"
  		for plugin in $WITH_PLUGINS; do
  			plugin_config="$BUILDROOT_CONFIGS/plugin-$plugin"
  			if [ -f "$plugin_config" ]; then
  				merge_configs+=("$plugin_config")
  			else
  				log_error "Plugin config not found: $plugin_config"
  				exit 1
  			fi
  		done
  	fi

  	"$BUILDROOT_GIT"/support/kconfig/merge_config.sh "${merge_configs[@]}"
    popd > /dev/null
}

prepare_variant() {
	variant_env $1
	buildroot_prepare "$br_builddir" "defconfig_variant $variant"
}

build_variant() {
	variant_env $1
	buildroot_build_if_needed "$br_builddir" "make" "$br_image"
}

rebuild_variant() {
	variant_env $1
	buildroot_build_always "$br_builddir" "make"
}

clean_variant() {
	variant_env $1
	rm -rf "$br_builddir"
}

package_variant() {
	variant_env $1

	mkdir -p "$BUILD_PACKAGE"

	# Build or update uImage from zImage
	if [ -f "$br_builddir/images/zImage" ]; then
		if [ ! -f "$br_builddir/images/uImage" ] || [ "$br_builddir/images/zImage" -nt "$br_builddir/images/uImage" ]; then
			if [ -x "$br_builddir/host/bin/mkimage" ]; then
				"$br_builddir/host/bin/mkimage" -A arm -O linux -T kernel -C none -a 0x40008000 -e 0x40008000 -n "Linux-6.6" \
					-d "$br_builddir/images/zImage" "$br_builddir/images/uImage"
			fi
		fi
	fi

	# Compress rootfs.ext4 to rootfs.ext4.xz
	if [ -f "$br_builddir/images/rootfs.ext4" ]; then
		rm -f "$br_builddir/images/rootfs.ext4.xz"
		xz -cT`nproc` "$br_builddir/images/rootfs.ext4" > "$br_builddir/images/rootfs.ext4.xz"
	fi

	# Copy and compress full system image if generated
	if [ -f "$br_builddir/images/ad5m-system.img" ]; then
		raw_image_name="Adventurer5M-System-$GIT_VERSION-$variant$mcu_suffix$plugin_suffix.img.xz"
		xz -cT`nproc` "$br_builddir/images/ad5m-system.img" > "$BUILD_PACKAGE/$raw_image_name"
		log_info "variant-$variant: created raw image $raw_image_name"
	fi

	# variant_env already resolved the mcu and plugin suffixes
	package_name="Adventurer5M-KlipperMod-$GIT_VERSION-$variant$mcu_suffix$plugin_suffix.tgz"
	package_name_pro="Adventurer5MPro-KlipperMod-$GIT_VERSION-$variant$mcu_suffix$plugin_suffix.tgz"

	# Package installer with U-Boot, kernel, DTBs, boot script, and rootfs
	install_files=()
	for f in rootfs.ext4.xz u-boot-sunxi-with-spl.bin uImage zImage boot.scr sunxi.dtb sun8i-t113s3-flashforge-ad5m.dtb sun8i-t113s4-flashforge-ad5m.dtb; do
		if [ -f "$br_builddir/images/$f" ]; then
			install_files+=("./$f")
		fi
	done

	# Fallback to rootfs.tar / chroot.tar.xz if legacy build
	if [ ${#install_files[@]} -eq 0 ] && [ -f "$br_image" ]; then
		rm -f "$br_chroot"
		xz -cT`nproc` "$br_image" > "$br_chroot"
		install_files+=("./chroot.tar.xz")
	fi

	tar -cf "$BUILD_PACKAGE/$package_name" -C "$GIT_ROOT/device_files/install" . -C "$br_builddir/images/" "${install_files[@]}"
	cp "$BUILD_PACKAGE/$package_name" "$BUILD_PACKAGE/$package_name_pro"
	log_info "variant-$variant: created $package_name"
}

##############################
###### Misc Build Steps ######
##############################

package_uninstall()
{
	package_name="Adventurer5M-KlipperMod-uninstall.tgz"
	package_name_pro="Adventurer5MPro-KlipperMod-uninstall.tgz"
	tar -cf "$BUILD_PACKAGE/$package_name" -C "$GIT_ROOT/device_files/uninstall" .
	cp "$BUILD_PACKAGE/$package_name" "$BUILD_PACKAGE/$package_name_pro"
	log_info "uninstall: created $package_name"
}

checksums()
{
	pushd $BUILD_PACKAGE > /dev/null
	rm -f md5sums
	md5sum * > md5sums
	log_info "created checksums:"
	cat md5sums
	popd > /dev/null
}

cd $GIT_ROOT
GIT_VERSION=$(git describe)

# run command
$@
